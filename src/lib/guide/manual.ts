export type GuideGroupId = (typeof GUIDE_GROUPS)[number]['id'];
export type GuideNoteTone = 'tip' | 'warn' | 'danger';

export type GuideBlock =
  | { kind: 'p'; text: string }
  | { kind: 'h'; id: string; title: string }
  | { kind: 'steps'; items: string[] }
  | { kind: 'list'; items: string[] }
  | { kind: 'note'; tone: GuideNoteTone; text: string }
  | { kind: 'table'; headers: [string, string]; rows: [string, string][] }
  | { kind: 'split'; columns: { title: string; items: string[] }[] }
  | { kind: 'faq'; items: { id: string; q: string; a: string }[] }
  | { kind: 'figure'; src: string; alt: string; caption: string }
  | { kind: 'video'; src: string; poster: string; caption: string };

function shot(file: string, alt: string, caption: string): GuideBlock {
  const name = file.split('?')[0];
  return { kind: 'figure', src: `/guide/${name}?v=4`, alt, caption };
}

function clip(file: string, poster: string, caption: string): GuideBlock {
  const src = file.split('?')[0];
  const posterName = poster.split('?')[0];
  return {
    kind: 'video',
    src: `/guide/${src}?v=4`,
    poster: `/guide/${posterName}?v=4`,
    caption,
  };
}

