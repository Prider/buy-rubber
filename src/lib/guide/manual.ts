export function topicById(id: string): GuideTopic | undefined {
  return GUIDE_TOPICS.find((topic) => topic.id === id);
}

function blockText(block: GuideBlock): string {
  switch (block.kind) {
    case 'p':
    case 'note':
      return block.text;
    case 'h':
      return block.title;
    case 'steps':
    case 'list':
      return block.items.join(' ');
    case 'table':
      return [...block.headers, ...block.rows.flat()].join(' ');
    case 'split':
      return block.columns.map((column) => `${column.title} ${column.items.join(' ')}`).join(' ');
    case 'faq':
      return block.items.map((item) => `${item.q} ${item.a}`).join(' ');
    default:
      return '';
  }
}

function topicSearchText(topic: GuideTopic): string {
  return [
    topic.title,
    topic.summary,
    topic.menu ?? '',
    ...(topic.keywords ?? []),
    ...topic.blocks.map(blockText),
  ]
    .join(' ')
    .toLowerCase();
}

export function searchTopics(query: string): GuideTopic[] {
  const normalized = query.trim().toLowerCase();
  if (!normalized) return [];

  return GUIDE_TOPICS
    .map((topic) => {
      const title = topic.title.toLowerCase();
      const summary = topic.summary.toLowerCase();
      const body = topicSearchText(topic);
      let score = 0;
      if (title.includes(normalized)) score += 5;
      if (summary.includes(normalized)) score += 3;
      if ((topic.menu ?? '').toLowerCase().includes(normalized)) score += 2;
      if (body.includes(normalized)) score += 1;
      return { topic, score };
    })
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((item) => item.topic);
}
